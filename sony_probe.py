#!/usr/bin/env python3
"""Read Sony camera discovery metadata; never send camera control commands.

Uses only Python's standard library. Captures are generated by this Mac probe,
not by Creators' App. Run on the same LAN as the camera.
"""

import argparse
import datetime as dt
import hashlib
import ipaddress
import json
import pathlib
import socket
import time
import urllib.error
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET

MAX_XML = 1024 * 1024
SERVICE = "urn:schemas-sony-com:service:DigitalImaging:1"
UPNP = "{urn:schemas-upnp-org:device-1-0}"


def timestamp():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def local_ipv4(value):
    address = ipaddress.IPv4Address(value)
    if not address.is_private or address.is_loopback or address.is_unspecified:
        raise ValueError("Expected a private LAN IPv4 camera address")
    return str(address)


def discover(seconds=4):
    request = (
        'M-SEARCH * HTTP/1.1\r\nHOST: 239.255.255.250:1900\r\n'
        'MAN: "ssdp:discover"\r\nMX: 2\r\n'
        f'ST: {SERVICE}\r\n\r\n'
    ).encode("ascii")
    found = {}
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
        sock.bind(("", 0))
        sock.settimeout(0.4)
        sock.setsockopt(socket.IPPROTO_IP, socket.IP_MULTICAST_TTL, 2)
        sock.sendto(request, ("239.255.255.250", 1900))
        deadline = time.monotonic() + seconds
        while time.monotonic() < deadline:
            try:
                body, peer = sock.recvfrom(65535)
            except socket.timeout:
                continue
            lines = body.decode("utf-8", errors="replace").split("\r\n")
            if not lines[0].startswith("HTTP/1.1 200"):
                continue
            headers = {}
            for line in lines[1:]:
                if ":" in line:
                    key, value = line.split(":", 1)
                    headers[key.lower()] = value.strip()
            if headers.get("st") != SERVICE:
                continue
            try:
                peer_ip = local_ipv4(peer[0])
                location = checked_url(headers["location"], peer_ip)
            except (ValueError, KeyError):
                continue
            found[location] = {"host": peer_ip, "location": location,
                               "headers": headers, "observed_at": timestamp()}
    return list(found.values())


def checked_url(url, host):
    parsed = urllib.parse.urlsplit(url)
    if (parsed.scheme != "http" or parsed.hostname != host or
            parsed.username is not None or parsed.password is not None or
            parsed.fragment):
        raise ValueError("Metadata URL must stay on the discovered camera")
    return url


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        raise ValueError("Camera metadata redirects are not followed")


def fetch_xml(url, host, entries, output, filename):
    checked_url(url, host)
    request_headers = {"User-Agent": "SonyProtocolProbe/0.1", "Accept": "application/xml"}
    request = urllib.request.Request(url, headers=request_headers)
    # Local camera traffic must not go through a system/environment HTTP proxy.
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
    started_at, start = timestamp(), time.monotonic()
    with opener.open(request, timeout=5) as response:
        body = response.read(MAX_XML + 1)
        elapsed = (time.monotonic() - start) * 1000
        if len(body) > MAX_XML:
            raise ValueError("Camera XML exceeds the 1 MiB limit")
        root = ET.fromstring(body)
        response_headers = [{"name": k, "value": v} for k, v in response.headers.items()
                            if k.lower() not in ("set-cookie", "authorization")]
        entries.append({
            "startedDateTime": started_at, "time": elapsed,
            "request": {"method": "GET", "url": url, "httpVersion": "HTTP/1.1",
                        "cookies": [], "headers": [{"name": k, "value": v}
                                                      for k, v in request_headers.items()],
                        "queryString": [], "headersSize": -1, "bodySize": 0},
            "response": {"status": response.status, "statusText": response.reason,
                         "httpVersion": "HTTP/1.1", "cookies": [],
                         "headers": response_headers,
                         "content": {"size": len(body), "mimeType": "application/xml",
                                     "text": body.decode("utf-8")},
                         "redirectURL": "", "headersSize": -1, "bodySize": len(body)},
            "cache": {}, "timings": {"send": 0, "wait": elapsed, "receive": 0},
            "serverIPAddress": host,
            "_producer": "Mac urllib probe; total elapsed is in wait; subphases unmeasured",
        })
    (output / filename).write_bytes(body)
    return root, {"file": filename, "sha256": hashlib.sha256(body).hexdigest()}


def probe_port(host, port):
    result = {"port": port, "observed_at": timestamp()}
    try:
        with socket.create_connection((host, port), timeout=2) as sock:
            result["tcp_connect"] = "accepted"
            if port == 22:
                sock.settimeout(2)
                result["banner"] = sock.recv(256).decode("ascii", errors="replace").strip()
    except OSError as exc:
        result["error"] = str(exc)
    return result


def inspect_camera(candidate, output, entries):
    host = candidate["host"]
    root, identity_file = fetch_xml(candidate["location"], host, entries, output, "device.xml")
    device = root.find(f"{UPNP}device")
    if device is None or device.findtext(f"{UPNP}manufacturer") != "Sony Corporation":
        raise ValueError("Device does not identify itself as Sony Corporation")
    services = device.findall(f"{UPNP}serviceList/{UPNP}service")
    service = next((s for s in services if s.findtext(f"{UPNP}serviceType") == SERVICE), None)
    if service is None:
        raise ValueError("Sony DigitalImaging service was not advertised")
    path = service.findtext(f"{UPNP}SCPDURL")
    if not path:
        raise ValueError("Missing DigitalImaging description URL")
    url = urllib.parse.urljoin(candidate["location"], path)
    description, capability_file = fetch_xml(url, host, entries, output, "capabilities.xml")
    selected = {"X_ModelName", "X_FirmwareVersion", "X_ServerType", "X_ServerVersion",
                "X_PTP_Versions", "X_PTP_PairingNecessity", "X_PTP_MediaServerSupport",
                "X_PTP_ContentsTransferSupport", "X_PTP_RemoteControlSupport", "X_SSH_Support"}
    capabilities = {node.tag.rsplit("}", 1)[-1]: node.text
                    for node in description.iter()
                    if node.tag.rsplit("}", 1)[-1] in selected}
    return {"identity": device.findtext(f"{UPNP}friendlyName"),
            "host": host, "discovery": candidate, "advertised_capabilities": capabilities,
            "ports": [probe_port(host, 22), probe_port(host, 15740)],
            "artifacts": [identity_file, capability_file]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", type=local_ipv4, help="Known camera IP; otherwise use Sony SSDP discovery")
    parser.add_argument("--port", type=int, default=64321, help="HTTP metadata port for --host")
    parser.add_argument("--out", type=pathlib.Path, default=pathlib.Path("evidence") / dt.datetime.now().strftime("probe-%Y%m%d-%H%M%S"))
    args = parser.parse_args()
    if not 1 <= args.port <= 65535:
        parser.error("port must be between 1 and 65535")
    args.out.mkdir(parents=True, exist_ok=False, mode=0o700)
    candidates = ([{"host": args.host, "location": f"http://{args.host}:{args.port}/dd.xml",
                    "source": "explicit host"}] if args.host else discover())
    entries, results, errors = [], [], []
    for index, candidate in enumerate(candidates):
        target = args.out / f"camera-{index + 1}"
        target.mkdir(mode=0o700)
        try:
            results.append(inspect_camera(candidate, target, entries))
        except (OSError, ValueError, ET.ParseError) as exc:
            errors.append({"host": candidate["host"], "error": str(exc)})
    report = {"captured_at": timestamp(), "producer": "sony_probe.py on Mac",
              "capture_scope": "Our metadata requests, not Creators' App traffic",
              "cameras": results, "errors": errors,
              "limitations": ["Advertisements do not verify authenticated camera commands.",
                              "No login, pairing, capture, parameter write or media download was attempted.",
                              "Port results describe only the camera state during this probe."]}
    (args.out / "report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    archive = {"log": {"version": "1.2", "creator": {"name": "SonyProtocolProbe", "version": "0.1"},
                       "entries": entries}}
    (args.out / "metadata.har").write_text(json.dumps(archive, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps(report, indent=2, ensure_ascii=False))
    print(f"Evidence directory: {args.out.resolve()}")
    return 0 if results else 1


if __name__ == "__main__":
    raise SystemExit(main())
